function Table({ head, rows }: { head: string[]; rows: Row[] }) {
  return (
    <div className="aty-tbl">
      <table>
        <thead><tr>{head.map((h, i) => <th key={i}>{h}</th>)}</tr></thead>
        <tbody>
          {rows.map((r, i) => (
            <tr key={i}>{r.map((c, j) => <td key={j}>{c}</td>)}</tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}

function List({ items }: { items: React.ReactNode[] }) {
  return <ul className="aty-list">{items.map((t, i) => <li key={i}>{t}</li>)}</ul>;
}

// 小標旁標出對應的投影片編號，方便對照原簡報
function H3({ slide, children }: { slide?: string; children: React.ReactNode }) {
  return <h3>{children}{slide && <span className="aty-slide">{slide}</span>}</h3>;
}

function Key({ children }: { children: React.ReactNode }) {
  return <div className="aty-key">{children}</div>;
}

function Cards({ items }: { items: { title: string; body: React.ReactNode }[] }) {
  return (
    <div className="aty-grid">
      {items.map((c) => <div key={c.title} className="aty-card"><b>{c.title}</b>{c.body}</div>)}
    </div>
  );
}

// 投影片每個單元最後一頁的「單元總結」
function Summary({ slide, title = "單元總結", items }: { slide?: string; title?: string; items: React.ReactNode[] }) {
  return (
    <div className="aty-sum">
      <div className="aty-sum-title">{title}{slide && <span className="aty-slide">{slide}</span>}</div>
      <ol>{items.map((t, i) => <li key={i}>{t}</li>)}</ol>
    </div>
  );
}

// 操作方向標籤：綠＝機會、黃＝等待觀察、紅＝避開
function Tag({ kind, children }: { kind: "go" | "wait" | "stop"; children: React.ReactNode }) {
  return <span className={`aty-tag ${kind}`}>{children}</span>;
}

function Dot({ color }: { color: string }) {
  return <span className="aty-dot" style={{ background: color }} />;
}

function Section({ id, no, title, children }: { id: string; no: string; title: string; children: React.ReactNode }) {
  return (
    <section id={id} className="aty-sec">
      <div className="aty-sec-head">
        <span className="aty-badge">{no}</span>
        <h2>{title}</h2>
      </div>
      {children}
    </section>
  );
}

function Part({ no, title }: { no: string; title: string }) {
  return <div className="aty-part"><span>{no}</span><h2>{title}</h2></div>;
}

